#pragma once

// The supported client's API surface: enums, items and class members from
// player reflection, refreshed with its API dump and binary strings. Generated
// into RobloxApiData.cpp by tools/gen_script_api.py. The Enum global is built
// from this, and Instance lookups use it to tell members the engine doesn't
// implement yet from ones that don't exist.

#include <cstdint>
#include <optional>
#include <span>
#include <string_view>

namespace lunar::lua::api {

struct EnumItemData {
    std::string_view name;
    std::uint32_t value;
};

// Items are sorted by value (then name), the order GetEnumItems returns.
struct EnumData {
    std::string_view name;
    std::uint32_t first;
    std::uint32_t count;
};

// An old name of a renamed item that still finds it (Enum.Font.GothamSemibold).
struct EnumLegacyName {
    std::string_view enumName;
    std::string_view legacy;
    std::string_view current;
};

enum class MemberKind : std::uint8_t { Property, Function, YieldFunction, Callback, Event };

struct MemberData {
    std::string_view name;
    MemberKind kind;
    std::string_view type; // properties: Luau type, "Enum.X" or a class name; empty otherwise
    // The capability reading (or calling, connecting) and writing it needs,
    // as the client's capability bit + 1 (1 Plugin, 2 LocalUser, 3 WritePlayer,
    // 4 RobloxScript, 5 RobloxEngine, 6 NotAccessible); 0 for none.
    std::uint8_t readCapability = 0;
    std::uint8_t writeCapability = 0;
    // A property Roblox keeps from scripts (NotScriptable, or one only the
    // player has, as BasePart.siz): not a member to index unless the
    // console's setscriptable says so; gethiddenproperty reaches it.
    bool scriptable = true;
};

// The client's name for a capability as MemberData numbers it ("Plugin").
std::string_view capabilityName(std::uint8_t capability);

// What a thread may reach, as a set of the capabilities above: bit 0 Plugin,
// bit 1 LocalUser, ... bit 5 NotAccessible. The numbers are the bits the client
// negotiates with its server.
using Capabilities = std::uint32_t;
inline constexpr Capabilities allCapabilities = (1u << 6) - 1;

// The identity levels the console's getidentity() reports, as the client
// names them (0x1068df9b7: Anonymous, LocalGUI, GameScript,
// ElevatedGameScript, CommandBar, StudioPlugin, ElevatedStudioPlugin,
// WebService, Replicator). The game's own scripts run as Basic (2), with none
// of the capabilities; the menu's Luau tab runs as Full (8), with every one.
enum class Identity : std::uint8_t { None = 0, Basic = 2, Full = 8 };

// What a level may reach: every capability at Full, none at Basic and below.
// GUESS: the levels between, whose table wasn't found: 3 and 6 (the elevated
// ones) Plugin, LocalUser and RobloxScript, 4 Plugin and LocalUser, 5 Plugin,
// 7 all but NotAccessible.
Capabilities capabilitiesOf(Identity identity);

enum ClassFlags : std::uint8_t { ClassCreatable = 1, ClassService = 2 };

struct ClassData {
    std::string_view name;
    std::string_view base; // empty at the root (Instance)
    std::uint32_t first;
    std::uint32_t count;
    std::uint8_t flags;
};

// Sorted by name.
std::span<const EnumData> allEnums();
std::span<const EnumItemData> itemsOf(const EnumData& data);
// Sorted by enum, then old name.
std::span<const EnumLegacyName> legacyEnumNames();
std::span<const ClassData> allClasses();
// Sorted by name; only what the class itself declares.
std::span<const MemberData> membersOf(const ClassData& data);

const EnumData* findEnum(std::string_view name);
const ClassData* findClass(std::string_view name);
// Searches the class and then its bases.
const MemberData* findMember(std::string_view className, std::string_view member);
// The class that declares a member findMember returned.
std::string_view declaringClass(const MemberData& member);
// Whether className is base or derives from it.
bool isA(std::string_view className, std::string_view base);

// What an event passes its handlers, from the API dump (RobloxEventData.cpp,
// generated by tools/gen_event_parameters.py): each parameter's name and the
// engine's name for its type (BasePart, Vector3, float, Tuple).
struct EventParameter {
    std::string_view name;
    std::string_view type;
};
// Searches the class and then its bases; none when no class has the event.
std::optional<std::span<const EventParameter>> eventParameters(std::string_view className, std::string_view event);

} // namespace lunar::lua::api
