#!/usr/bin/env python3
"""Generates the events' parameters (RobloxEventData.cpp) from the supported
release's official API dump: each event's parameter names and types, as the
console's getsignalarguments and getsignalargumentsinfo answer them. The types
are the dump's own names (BasePart, Vector3, float, Tuple), which are the
engine's reflection names.

    tools/gen_event_parameters.py --api-dump API-Dump.json [--output RobloxEventData.cpp]

The dump is the one RobloxApiData.cpp was generated from (its SHA-256 is in
that file's header); the generated output is checked in.
"""

import argparse
import hashlib
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
version = re.search(r'robloxVersion\[\] = "([^"]+)"',
                    (root / "engine/include/lunar/RobloxVersion.hpp").read_text())[1]
parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("--api-dump", type=pathlib.Path, required=True)
parser.add_argument("--output", type=pathlib.Path, default=root / "script/src/RobloxEventData.cpp")
args = parser.parse_args()
api_dump = json.loads(args.api_dump.read_text())

events = []
for cls in api_dump["Classes"]:
    for member in cls["Members"]:
        if member["MemberType"] == "Event":
            params = [(p["Name"], p["Type"]["Name"]) for p in member.get("Parameters", [])]
            events.append((cls["Name"], member["Name"], params))
events.sort(key=lambda e: (e[0], e[1]))

lines = [
    f"// Generated by tools/gen_event_parameters.py for Roblox {version}.",
    f"// API dump SHA-256: {hashlib.sha256(args.api_dump.read_bytes()).hexdigest()}",
    "// Do not edit by hand; see tools/gen_event_parameters.py for regeneration.",
    "",
    '#include "RobloxApi.hpp"',
    "",
    "#include <algorithm>",
    "#include <tuple>",
    "",
    "namespace lunar::lua::api {",
    "",
    "// clang-format off",
    "namespace {",
    "",
    "struct EventData {",
    "    std::string_view className;",
    "    std::string_view event;",
    "    std::uint32_t first;",
    "    std::uint32_t count;",
    "};",
    "",
    "constexpr EventParameter eventParameterData[] = {",
]
rows = []
offset = 0
for cls, event, params in events:
    for name, type_name in params:
        lines.append(f'    {{"{name}", "{type_name}"}},')
    rows.append(f'    {{"{cls}", "{event}", {offset}, {len(params)}}},')
    offset += len(params)
lines += ["};", "", "// Sorted by class, then event.", "constexpr EventData eventData[] = {"] + rows + ["};", ""]
lines += [
    "} // namespace",
    "// clang-format on",
    "",
    "std::optional<std::span<const EventParameter>> eventParameters(std::string_view className, std::string_view event)",
    "{",
    "    for (const ClassData* data = findClass(className); data; data = data->base.empty() ? nullptr : findClass(data->base)) {",
    "        const auto key = std::tuple(data->name, event);",
    "        const auto* found = std::ranges::lower_bound(eventData, key, {}, [](const EventData& e) {",
    "            return std::tuple(e.className, e.event);",
    "        });",
    "        if (found != std::end(eventData) && found->className == data->name && found->event == event)",
    "            return std::span(eventParameterData).subspan(found->first, found->count);",
    "    }",
    "    return std::nullopt;",
    "}",
    "",
    "} // namespace lunar::lua::api",
    "",
]
args.output.write_text("\n".join(lines))
print(f"{args.output}: {len(events)} events")
